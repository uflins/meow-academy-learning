// 回傳加了注音的元素；字典裡沒有的字照常顯示
export function zy(text) {
  return h('span', { class: 'zy' }, [...text].map((ch) => (ZY[ch]
    ? h('ruby', {}, ch, h('rt', {}, ZY[ch]))
    : ch)));
}
